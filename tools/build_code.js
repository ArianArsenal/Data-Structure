#!/usr/bin/env node
/* Reads the tagged sources in src/{python,cpp,java} and writes
 * site/js/generated/code.js (window.DS_CODE) for the visualizer.
 *
 * Markers (whole-line comments):  # @op <name>   ...   # @endop
 * Step tags (end of a code line): # @step <id>[,<id>...]
 * Markers and tags are stripped from the displayed code. */
'use strict';
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'site/js/generated/code.js');

// Visualizer id -> source file base names, one per language.
const pascal = (id) => id.replace(/(^|-)(\w)/g, (_, __, c) => c.toUpperCase());
const snake = (id) => id.replace(/-/g, '_');
// Overrides avoid clashes with standard library names (Python's queue, java.util.*).
const FILE_NAMES = {
  bst: { java: 'BST' },
  stack: { python: 'array_stack', cpp: 'array_stack', java: 'ArrayStack' },
  queue: { python: 'circular_queue', cpp: 'circular_queue', java: 'CircularQueue' },
  deque: { python: 'circular_deque', cpp: 'circular_deque', java: 'CircularDeque' },
  'priority-queue': { java: 'MaxPriorityQueue' },
  'avl-tree': { java: 'AVLTree' },
  'lru-cache': { java: 'LRUCache' },
  'b-tree': { java: 'BTree' },
};
function filesFor(id) {
  const o = FILE_NAMES[id] || {};
  return {
    python: `src/python/${o.python || snake(id)}.py`,
    cpp: `src/cpp/${o.cpp || snake(id)}.h`,
    java: `src/java/${o.java || pascal(id)}.java`,
  };
}

const OP_RE = /^\s*(?:#|\/\/)\s*@op\s+(\w+)\s*$/;
const END_RE = /^\s*(?:#|\/\/)\s*@endop\s*$/;
const STEP_RE = /\s*(?:#|\/\/)\s*@step\s+([\w,]+)\s*$/;

function parse(file) {
  const raw = fs.readFileSync(path.join(ROOT, file), 'utf8').replace(/\r\n/g, '\n').split('\n');
  if (raw[raw.length - 1] === '') raw.pop();
  const lines = [];
  const ops = {};
  let op = null;
  raw.forEach((line, n) => {
    const where = `${file}:${n + 1}`;
    let m;
    if ((m = OP_RE.exec(line))) {
      if (op) throw new Error(`${where}: @op ${m[1]} inside @op ${op.name}`);
      op = { name: m[1], start: lines.length, steps: {} };
      return;
    }
    if (END_RE.test(line)) {
      if (!op) throw new Error(`${where}: @endop without @op`);
      // Trim blank lines at the region's end.
      let end = lines.length;
      while (end > op.start && !lines[end - 1].trim()) end--;
      ops[op.name] = { start: op.start, end, steps: op.steps };
      op = null;
      return;
    }
    if ((m = STEP_RE.exec(line))) {
      if (!op) throw new Error(`${where}: @step outside an @op region`);
      for (const id of m[1].split(',')) (op.steps[id] = op.steps[id] || []).push(lines.length);
      line = line.slice(0, m.index);
    }
    lines.push(line.replace(/\s+$/, ''));
  });
  if (op) throw new Error(`${file}: missing @endop for ${op.name}`);
  return { file: path.basename(file), lines, ops };
}

const CORE = ['dsv', 'highlight', 'codepanel', 'watch', 'scene', 'layouts', 'helpers', 'graph', 'player', 'app'];
const page = (id) => `<!doctype html>
<html lang="en" data-theme="dark">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1">
  <title>DS Visualizer</title>
  <link rel="stylesheet" href="../css/theme.css">
</head>
<body>
  <div id="app"></div>
  <!-- GENERATED by tools/build_code.js -->
  <script src="../js/generated/code.js"></script>
${CORE.map((f) => `  <script src="../js/core/${f}.js"></script>`).join('\n')}
  <script src="../js/ds/${id}.js"></script>
  <script>DSV.mount('${id}');</script>
</body>
</html>
`;

function main() {
  const ids = fs
    .readdirSync(path.join(ROOT, 'site/js/ds'))
    .filter((f) => f.endsWith('.js'))
    .map((f) => f.slice(0, -3))
    .sort();
  const all = {};
  for (const id of ids) {
    const files = filesFor(id);
    all[id] = {};
    for (const lang of Object.keys(files)) {
      if (!fs.existsSync(path.join(ROOT, files[lang]))) throw new Error(`${id}: missing ${files[lang]}`);
      all[id][lang] = parse(files[lang]);
    }
  }
  const body =
    '/* GENERATED by tools/build_code.js from src/. Do not edit. */\n' +
    'window.DS_CODE = ' +
    JSON.stringify(all) +
    ';\n';
  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, body);
  fs.writeFileSync(
    path.join(path.dirname(OUT), 'ready.js'),
    '/* GENERATED by tools/build_code.js. */\nwindow.DS_READY = ' + JSON.stringify(ids) + ';\n'
  );
  for (const id of ids) fs.writeFileSync(path.join(ROOT, 'site/ds', id + '.html'), page(id));
  console.log(`build_code: ${ids.length} structures -> ${path.relative(ROOT, OUT)}`);
  return all;
}

module.exports = { main, parse, filesFor };
if (require.main === module) {
  try {
    main();
  } catch (e) {
    console.error('build_code: ' + e.message);
    process.exit(1);
  }
}
